    # Construct the exact expected filename format
    filename = f"molingo_sample{sample_number}_repeat0.mp4"
    mp4_path = os.path.join(mp4_folder, filename)

    # Fallback option if your file follows the Category-ID structure instead (e.g., C1-01_repeat0.mp4)
    if not os.path.exists(mp4_path) and sample_number == 1:
        mp4_path = os.path.join(mp4_folder, "C1-01_repeat0.mp4")

    if not os.path.exists(mp4_path):
        print(f"❌ Error: Could not find the MP4 file at: {mp4_path}")
        return

    print(f"🎬 Streaming pre-rendered video canvas for Sample {sample_number}...")

    # Read and encode the video file to base64 format for inline HTML display
    with open(mp4_path, "rb") as f:
        video_bytes = f.read()
        b64_video = base64.b64encode(video_bytes).decode("ascii")

