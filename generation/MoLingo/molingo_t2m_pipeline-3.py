def render_fallback_gif(motion_data, title_text, output_path):
    import matplotlib.pyplot as plt
    import matplotlib.animation as animation
    fig = plt.figure(figsize=(4, 4))
    ax = fig.add_subplot(111, projection='3d')
    ax.set_xlim3d([-1, 1]); ax.set_ylim3d([-1, 1]); ax.set_zlim3d([-0.2, 1.8])
    ax.set_title(title_text, fontsize=8)

    # HumanML3D Standard Joint connections
    SKELETON_BONES = [
        (0, 1), (1, 4), (4, 7), (7, 10),                 # Right Leg
        (0, 2), (2, 5), (5, 8), (8, 11),                 # Left Leg
        (0, 3), (3, 6), (6, 9), (9, 12), (12, 15),       # Spine / Neck / Head
        (9, 13), (13, 16), (16, 18), (18, 20),           # Left Arm
        (9, 14), (14, 17), (17, 19), (19, 21)            # Right Arm
    ]

    lines = [ax.plot([], [], [], color='blue', linewidth=2)[0] for _ in SKELETON_BONES]

    def update(frame):
        frame_data = motion_data[frame]
        for line, (joint_a, joint_b) in zip(lines, SKELETON_BONES):
            if joint_a < frame_data.shape[0] and joint_b < frame_data.shape[0]:
                x = [frame_data[joint_a, 0], frame_data[joint_b, 0]]
                y = [frame_data[joint_a, 2], frame_data[joint_b, 2]]
                z = [frame_data[joint_a, 1], frame_data[joint_b, 1]]
                line.set_data(x, y)
                line.set_3d_properties(z)
        return lines

    ani = animation.FuncAnimation(fig, update, frames=len(motion_data), interval=50, blit=True)
    plt.close(fig)
    ani.save(output_path, writer='pillow', fps=20)

